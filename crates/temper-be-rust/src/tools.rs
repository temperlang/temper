//! How Rust runs built libraries' tests, for `temper test -b rust`:
//! Cargo (`CARGO`), offline, on one workspace for every library built in
//! `temper.out/rust` ([`workspace`]), with one target directory,
//! `temper.out/rust/target`, so a crate that several libraries use (a
//! library, std, temper-core) is built once for them all, and all of
//! them at once. Each library's tests build with the others'
//! (`cargo build --tests`), then its test programs run alone, as
//! `cargo test` would run them, and what they print is read. Where that
//! workspace doesn't load, or a library's tests don't build there, it's
//! `cargo test` in the library's own crate, as before, which says what's
//! wrong. `temper run -b rust` builds the library's program
//! (`src/main.rs`) the same way, quietly, then runs it, as Kotlin's
//! `cargo run` does.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use temper_tmpl::files::write_if_changed;
use temper_tmpl::tools::{output, program, step, tool, tool_output};
use temper_tmpl::{TestResults, Tested, Tools};

pub const TOOLS: Tools = Tools {
    prepare: Some(workspace),
    build_dirs: &[".build", "target"],
    note: None,
    test,
    run,
};

/// The workspace's directory in `temper.out/rust`, a name no library's
/// directory has: its `Cargo.toml` and `Cargo.lock`, and a link to each
/// crate there.
const WORKSPACE: &str = ".build";

/// Writes a Cargo workspace over every library built in `dir`, from the
/// crates' own directories, unchanged: a workspace's members are below
/// it, so it links to each crate directory in `dir` (std's and
/// temper-core's too, which libraries' path dependencies name, `../std`
/// from a link reaching the link beside it), and its members are the
/// libraries. Each crate stays a package of its own, whose `cargo build`
/// is just as before. It's kept from run to run, with its lockfile, as
/// is the target directory, so Cargo rebuilds only the crates whose
/// files `temper build` rewrote, or whose tools or flags changed, as it
/// tracks them itself. Where it doesn't load (it can't
/// link, the libraries' packages clash, or their dependencies aren't
/// there offline), it's removed, and libraries build alone; that's never
/// an error here, as each library's own build says what's wrong.
fn workspace(dir: &Path, all: &[Tested]) -> Result<(), String> {
    let root = dir.join(WORKSPACE);
    // What the last run built, which this one builds again.
    let _ = std::fs::remove_file(root.join(BUILT));
    let members: Vec<String> = (all.iter())
        .filter(|l| dir.join(&l.name).join("Cargo.toml").is_file())
        .map(|l| temper_tmpl::json_string(&l.name))
        .collect();
    let text = format!(
        "# Generated by Temper for `temper test -b rust` and `temper run -b rust`:
# every library in the directory above, linked here, in one workspace, so
# each crate is built once.
[workspace]
resolver = \"2\"
members = [{}]
",
        members.join(", ")
    );
    let loaded = std::fs::create_dir_all(&root).is_ok()
        && link_crates(dir, &root).is_ok()
        && write_if_changed(&root.join("Cargo.toml"), text.as_bytes()).is_ok()
        && output(
            Command::new(tool("CARGO", "cargo"))
                .args(["metadata", "--offline", "--format-version", "1"])
                .current_dir(&root),
            "cargo metadata",
        )
        .is_ok_and(|o| o.status.success());
    if !loaded {
        let _ = std::fs::remove_dir_all(&root);
    }
    Ok(())
}

/// Links each crate directory in `dir` (one with a `Cargo.toml`) from
/// `root`, by its name, where it isn't yet, and removes links to those
/// that are gone.
fn link_crates(dir: &Path, root: &Path) -> std::io::Result<()> {
    for entry in std::fs::read_dir(root)? {
        let at = entry?.path();
        let link = std::fs::symlink_metadata(&at).is_ok_and(|m| m.file_type().is_symlink());
        if link && !at.join("Cargo.toml").is_file() {
            std::fs::remove_file(&at).or_else(|_| std::fs::remove_dir(&at))?;
        }
    }
    for entry in std::fs::read_dir(dir)? {
        let entry = entry?;
        let name = entry.file_name();
        let at = root.join(&name);
        let linked = std::fs::symlink_metadata(&at).is_ok();
        if name != WORKSPACE && !linked && entry.path().join("Cargo.toml").is_file() {
            link_dir(&Path::new("..").join(&name), &at)?;
        }
    }
    Ok(())
}

#[cfg(unix)]
fn link_dir(to: &Path, at: &Path) -> std::io::Result<()> {
    std::os::unix::fs::symlink(to, at)
}

/// Windows lets only some users link, by default; others build alone.
#[cfg(windows)]
fn link_dir(to: &Path, at: &Path) -> std::io::Result<()> {
    std::os::windows::fs::symlink_dir(to, at)
}

#[cfg(not(any(unix, windows)))]
fn link_dir(_: &Path, _: &Path) -> std::io::Result<()> {
    Err(std::io::ErrorKind::Unsupported.into())
}

/// The workspace's directory, where [`workspace`] made it.
fn workspace_root(dir: &Path) -> Option<PathBuf> {
    let root = dir.join(WORKSPACE);
    root.join("Cargo.toml").is_file().then_some(root)
}

fn package(library: &Tested) -> String {
    crate::translate::rust_name(&library.name, &library.metadata)
}

fn run(dir: &Path, library: &Tested, _: &[Tested]) -> Result<bool, String> {
    let target = std::path::absolute(dir.join("target")).map_err(|e| e.to_string())?;
    // The package's binary, as its config may name it ([`crate::bin_name`]).
    let package = package(library);
    let bin = crate::bin_name(&package);
    let mut build = Command::new(tool("CARGO", "cargo"));
    build
        .args(["build", "--offline", "--bin", &bin])
        .env("CARGO_TARGET_DIR", &target);
    match workspace_root(dir) {
        Some(root) => build.args(["-p", &package]).current_dir(root),
        None => build.current_dir(dir.join(&library.name)),
    };
    step(&mut build, "cargo build")?;
    let exe = target
        .join("debug")
        .join(format!("{bin}{}", std::env::consts::EXE_SUFFIX));
    program(&mut Command::new(exe), &library.name)
}

fn test(dir: &Path, library: &Tested, all: &[Tested]) -> TestResults {
    let target = std::path::absolute(dir.join("target")).map_err(|e| e.to_string())?;
    let cargo = tool("CARGO", "cargo");
    let Some(root) = workspace_root(dir) else {
        let run = output(
            Command::new(&cargo)
                .args(["test", "--offline"])
                .env("CARGO_TARGET_DIR", target)
                .current_dir(dir.join(&library.name)),
            "cargo",
        )?;
        return results(&run);
    };
    let programs = test_programs(&built_tests(&cargo, &root, &target, all)?, &library.name);
    if programs.is_empty() {
        // Its tests didn't build: `cargo test` says why.
        let run = output(
            Command::new(&cargo)
                .args(["test", "--offline", "-p", &package(library)])
                .env("CARGO_TARGET_DIR", target)
                .current_dir(&root),
            "cargo",
        )?;
        return results(&run);
    }
    // Each in its package's directory, as `cargo test` runs it.
    let mut ran = Output {
        status: std::process::ExitStatus::default(),
        stdout: Vec::new(),
        stderr: Vec::new(),
    };
    for exe in programs {
        let run = output(
            Command::new(exe).current_dir(root.join(&library.name)),
            "the tests",
        )?;
        ran.stdout.extend(run.stdout);
        ran.stderr.extend(run.stderr);
    }
    results(&ran)
}

/// Builds every tested library's tests in the workspace `root` at once,
/// so they share one set of features, and all build together; what Cargo
/// said it built, as JSON, kept in [`BUILT`] for the libraries after the
/// first, which a build again would only say again (or fail again, for
/// a library that doesn't build).
fn built_tests(cargo: &str, root: &Path, target: &Path, all: &[Tested]) -> Result<String, String> {
    let kept = root.join(BUILT);
    if let Ok(json) = std::fs::read_to_string(&kept) {
        return Ok(json);
    }
    let mut build = Command::new(cargo);
    build.args([
        "build",
        "--offline",
        "--tests",
        "--keep-going",
        "--message-format=json-render-diagnostics",
    ]);
    for library in all.iter().filter(|l| l.tests > 0) {
        build.args(["-p", &package(library)]);
    }
    let built = output(
        build.env("CARGO_TARGET_DIR", target).current_dir(root),
        "cargo build",
    )?;
    let json = String::from_utf8_lossy(&built.stdout).into_owned();
    let _ = std::fs::write(&kept, &json);
    Ok(json)
}

/// Where [`built_tests`] keeps what Cargo built, in the workspace, for
/// one run: [`workspace`] removes it.
const BUILT: &str = "tests-built.json";

/// The test programs Cargo built, from its JSON messages, for the library
/// in the workspace's directory `name`: its library's and its program's.
fn test_programs(json: &str, name: &str) -> Vec<PathBuf> {
    let mut programs = Vec::new();
    for line in json.lines() {
        if !line.starts_with("{\"reason\":\"compiler-artifact\"") {
            continue;
        }
        let (Some(manifest), Some(exe)) = (
            json_field(line, "manifest_path"),
            json_field(line, "executable"),
        ) else {
            continue;
        };
        // A test build's profile says so; the target's own `test` doesn't.
        let profile = line.split_once("\"profile\":{").map(|(_, p)| p);
        let profile = profile.and_then(|p| p.split_once('}')).map(|(p, _)| p);
        let manifest = Path::new(&manifest);
        let dir = manifest
            .parent()
            .filter(|d| d.file_name() == Some(name.as_ref()));
        let in_workspace = dir.and_then(Path::parent).and_then(Path::file_name);
        if in_workspace == Some(WORKSPACE.as_ref())
            && profile.is_some_and(|p| p.contains("\"test\":true"))
        {
            programs.push(PathBuf::from(exe));
        }
    }
    programs
}

/// A string field's value in a line of Cargo's JSON, by its key, wherever
/// it is; `None` where it isn't a string (`"executable":null`).
fn json_field(line: &str, key: &str) -> Option<String> {
    let (_, rest) = line.split_once(&format!("\"{key}\":\""))?;
    let mut value = String::new();
    let mut chars = rest.chars();
    loop {
        match chars.next()? {
            '"' => return Some(value),
            '\\' => match chars.next()? {
                'n' => value.push('\n'),
                't' => value.push('\t'),
                'r' => value.push('\r'),
                'b' => value.push('\u{8}'),
                'f' => value.push('\u{c}'),
                'u' => {
                    let hex: String = chars.by_ref().take(4).collect();
                    value.push(char::from_u32(u32::from_str_radix(&hex, 16).ok()?)?);
                }
                c => value.push(c),
            },
            c => value.push(c),
        }
    }
}

/// Each test's result, from what Rust's test programs printed.
fn results(run: &Output) -> TestResults {
    let stdout = String::from_utf8_lossy(&run.stdout);
    let mut results = Vec::new();
    for line in stdout.lines() {
        // `test tests::name ... ok`, or `... FAILED`.
        let Some(rest) = line.strip_prefix("test ") else {
            continue;
        };
        let Some((name, result)) = rest.rsplit_once(" ... ") else {
            continue;
        };
        let short = name.rsplit("::").next().unwrap_or(name).to_string();
        match result {
            "ok" => results.push((short, None)),
            "FAILED" => results.push((short, Some(failure(&stdout, name)))),
            _ => {}
        }
    }
    if results.is_empty() {
        return Err(format!("no test results\n{}", tool_output(run)));
    }
    Ok(results)
}

/// Why a Rust test failed, from its captured output: the message of the
/// error it returned (`Error: Error(Some(MessageError("expected …")))`),
/// or its panic's, else just that it failed.
fn failure(stdout: &str, name: &str) -> String {
    let header = format!("---- {name} stdout ----\n");
    let Some(at) = stdout.find(&header) else {
        return "failed".to_string();
    };
    let section = &stdout[at + header.len()..];
    let section = &section[..section.find("\n\n").unwrap_or(section.len())];
    if let Some((_, rest)) = section.split_once("MessageError(\"") {
        if let Some((message, _)) = rest.split_once("\")") {
            return message.replace("\\\"", "\"");
        }
    }
    let mut lines = section.lines();
    while let Some(line) = lines.next() {
        if line.contains(" panicked at ") {
            if let Some(message) = lines.next() {
                return message.to_string();
            }
        }
    }
    section.lines().next().unwrap_or("failed").to_string()
}

#[cfg(test)]
mod tests {
    use super::{failure, test_programs};
    use std::path::PathBuf;

    /// A Rust test's failure, from what `cargo test` prints.
    #[test]
    fn reads_rust_failures() {
        let out = "test r#mod::tests::b ... FAILED\n\nfailures:\n\n\
                   ---- r#mod::tests::b stdout ----\n\
                   Error: Error(Some(MessageError(\"expected 1 + 1 == (3) not (2)\")))\n\n";
        assert_eq!(
            failure(out, "r#mod::tests::b"),
            "expected 1 + 1 == (3) not (2)"
        );
        assert_eq!(failure(out, "r#mod::tests::c"), "failed");
    }

    /// A library's test programs, from what `cargo build --tests
    /// --message-format=json` prints: not another crate's, nor a
    /// program built to run, nor a library, which has no program.
    #[test]
    fn finds_test_programs() {
        let artifact = |manifest: &str, test: bool, exe: &str| {
            format!(
                "{{\"reason\":\"compiler-artifact\",\"package_id\":\"x\",\
                 \"manifest_path\":\"{manifest}\",\"target\":{{\"kind\":[\"lib\"],\
                 \"test\":true}},\"profile\":{{\"opt_level\":\"0\",\"test\":{test}}},\
                 \"executable\":{exe},\"fresh\":true}}\n"
            )
        };
        let json = [
            artifact("/o/rust/.build/a/Cargo.toml", true, "\"/o/t/deps/a-1\""),
            artifact("/o/rust/.build/a/Cargo.toml", false, "null"),
            artifact("/o/rust/.build/a/Cargo.toml", false, "\"/o/t/a\""),
            artifact("/o/rust/.build/b/Cargo.toml", true, "\"/o/t/deps/b-2\""),
            artifact("/o/rust/a/Cargo.toml", true, "\"/o/t/deps/a-3\""),
            artifact(
                "C:\\\\o\\\\.build\\\\a\\\\Cargo.toml",
                true,
                "\"C:\\\\t\\\\a-4.exe\"",
            ),
            "{\"reason\":\"build-finished\",\"success\":true}\n".to_string(),
        ]
        .concat();
        let mut expected = vec![PathBuf::from("/o/t/deps/a-1")];
        if cfg!(windows) {
            expected.push(PathBuf::from("C:\\t\\a-4.exe"));
        }
        assert_eq!(test_programs(&json, "a"), expected);
    }
}
