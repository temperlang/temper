//! How C++ runs built libraries' tests, for `temper test -b cpp`: CMake
//! (`CMAKE`) on one project for every library built in `temper.out/cpp`
//! ([`workspace`]), which adds each library's own `CMakeLists.txt`, so a
//! library that others use is built once for them all, as Rust's one
//! target directory shares crates. For each library it builds its
//! `LIBRARY-test` target, its tests with std and the libraries it
//! imports, by `g++` or whatever CMake finds (`CXX`), [`jobs`] at once,
//! then runs that program in the library's directory, which writes
//! `test-results.xml`, as Kotlin's `RunCpp` runs its `g++` build.
//! `temper run -b cpp` builds the `LIBRARY-main` target the same way,
//! quietly, and runs it. Where that project doesn't configure (a
//! library using one that didn't build), each library builds alone, in
//! `LIBRARY/build`, so one library's problem stays its own. Both build
//! through ccache where it's installed ([`ccache`]).

use std::ffi::OsStr;
use std::path::{Path, PathBuf};
use std::process::Command;
use temper_tmpl::files::write_if_changed;
use temper_tmpl::tools::{
    junit_file, limit_memory, output, program, reuse_or_clear, tool, tool_identity, tool_output,
    write_stamp,
};
use temper_tmpl::{TestResults, Tested, Tools};

pub const TOOLS: Tools = Tools {
    prepare: Some(workspace),
    build_dirs: &[".build", "*/build"],
    note: Some(note),
    test,
    run,
};

/// The shared build's directory in `temper.out/cpp`, a name no
/// library's directory has: its `CMakeLists.txt`, and the build in
/// `tree`, with the programs in `tree/bin`.
const WORKSPACE: &str = ".build";

/// Writes and configures one CMake project adding every library built in
/// `dir`, each where its own project would add it, so libraries that
/// several use are configured and built once; their own projects skip
/// a library already added (`if(NOT TARGET …)`). Programs all go to one
/// directory, wherever the library was added. It's kept from run to
/// run, as `temper build` rewrites only files that changed, so CMake
/// rebuilds only what they touch, unless the tools or their settings
/// changed ([`fresh`]). It's configured each run, which takes CMake a
/// fraction of a second once it's cached what it found, so a library's
/// changed `CMakeLists.txt` that doesn't configure is seen here. Where
/// it doesn't configure, it's removed, and libraries build alone;
/// that's never an error here, as each library's own build says what's
/// wrong.
fn workspace(dir: &Path, all: &[Tested]) -> Result<(), String> {
    let root = dir.join(WORKSPACE);
    let tree = root.join("tree");
    fresh(&root, &tree);
    let mut text = String::from(
        "# Generated by Temper for `temper test -b cpp` and `temper run -b cpp`:
# every library in the directory above, in one build, so each is built
# once.
cmake_minimum_required(VERSION 3.10)
project(temper-libraries LANGUAGES CXX)
set(CMAKE_RUNTIME_OUTPUT_DIRECTORY ${CMAKE_BINARY_DIR}/bin)
set(CMAKE_RUNTIME_OUTPUT_DIRECTORY_DEBUG ${CMAKE_BINARY_DIR}/bin)
",
    );
    for library in all {
        // Quoted, though names are dashed identifiers already.
        let name = crate::cmake_escaped(&library.name);
        text.push_str(&format!(
            "if(NOT TARGET \"{name}\")\n  add_subdirectory(\"${{CMAKE_CURRENT_SOURCE_DIR}}/../{name}\" \"{name}\")\nendif()\n"
        ));
    }
    let written = write_if_changed(&root.join("CMakeLists.txt"), text.as_bytes());
    let configured = written.is_ok()
        && output(
            Command::new(tool("CMAKE", "cmake"))
                .arg("-S")
                .arg(&root)
                .arg("-B")
                .arg(&tree)
                .arg("-DCMAKE_BUILD_TYPE=Debug")
                .args(launcher()),
            "cmake",
        )
        .is_ok_and(|o| o.status.success());
    match configured {
        true => write_stamp(&root.join(STAMP), &toolchain(&tree)),
        false => {
            let _ = std::fs::remove_dir_all(&root);
        }
    }
    Ok(())
}

/// A build directory's [`toolchain`], as it was last configured.
const STAMP: &str = "temper-toolchain";

/// What CMake reads from the environment only as it first configures a
/// build, or that changes what it finds then: the compiler and flags,
/// the generator, a toolchain file, where to find packages, and macOS's
/// SDK and Xcode (`DEVELOPER_DIR`, which `/usr/bin/c++` follows).
const CONFIGURE_VARS: [&str; 12] = [
    "CXX",
    "CXXFLAGS",
    "LDFLAGS",
    "CMAKE_CXX_COMPILER_LAUNCHER",
    "CMAKE_GENERATOR",
    "CMAKE_GENERATOR_PLATFORM",
    "CMAKE_GENERATOR_TOOLSET",
    "CMAKE_TOOLCHAIN_FILE",
    "CMAKE_PREFIX_PATH",
    "SDKROOT",
    "MACOSX_DEPLOYMENT_TARGET",
    "DEVELOPER_DIR",
];

/// What a build in `tree` depends on beyond its files, which CMake reads
/// only as it first configures it: CMake, the compiler, [`launcher`],
/// and each of [`CONFIGURE_VARS`]; and, once it's configured, the
/// compiler CMake found, as its cache names it, which tells a compiler
/// changed behind a shim such as `c++` where the shim itself didn't.
fn toolchain(tree: &Path) -> String {
    toolchain_with(&|name| std::env::var(name).unwrap_or_default(), tree)
}

/// [`toolchain`], with the environment's variables as `var` gives them.
fn toolchain_with(var: &dyn Fn(&str) -> String, tree: &Path) -> String {
    let cxx = Some(var("CXX")).filter(|c| !c.is_empty());
    let mut key = format!(
        "cmake {}\ncxx {}\nlauncher {}\n",
        tool_identity(&tool("CMAKE", "cmake")),
        tool_identity(cxx.as_deref().unwrap_or("c++")),
        launcher().join(" "),
    );
    for name in CONFIGURE_VARS {
        key.push_str(&format!("{name} {}\n", var(name)));
    }
    let cache = std::fs::read_to_string(tree.join("CMakeCache.txt")).unwrap_or_default();
    let found = (cache.lines())
        .filter_map(|line| line.strip_prefix("CMAKE_CXX_COMPILER:"))
        .find_map(|rest| rest.split_once('=').map(|(_, path)| path));
    if let Some(found) = found {
        key.push_str(&format!("found {}\n", tool_identity(found)));
    }
    key
}

/// Removes a build directory configured with another [`toolchain`] than
/// its tree's now, so it's configured and built afresh.
fn fresh(build: &Path, tree: &Path) {
    reuse_or_clear(build, &build.join(STAMP), &toolchain(tree));
}

/// How many compiles run at once unless `TEMPER_CXX_JOBS` says: one per
/// CPU, four at most, as a debug compile of generated C++ takes a few
/// hundred megabytes, up to 0.8 GB for Kelpto's biggest library, so
/// four keep within a small machine's memory beside other work.
pub const MAX_DEFAULT_JOBS: usize = 4;

/// How many compiles a C++ build runs at once (CMake's `-j`, and the C++
/// backend's own tests): `TEMPER_CXX_JOBS`, a whole number above 0,
/// where it's set and not empty, else one per CPU, up to
/// [`MAX_DEFAULT_JOBS`]; or what `TEMPER_CXX_JOBS` should be.
pub fn jobs() -> Result<usize, String> {
    let cpus = std::thread::available_parallelism().map_or(1, |n| n.get());
    choose_jobs(std::env::var("TEMPER_CXX_JOBS").ok().as_deref(), cpus)
}

/// [`jobs`], given `TEMPER_CXX_JOBS` and the CPUs.
fn choose_jobs(given: Option<&str>, cpus: usize) -> Result<usize, String> {
    match given {
        None | Some("") => Ok(cpus.clamp(1, MAX_DEFAULT_JOBS)),
        Some(text) => match text.parse() {
            Ok(n) if n > 0 && text.bytes().all(|b| b.is_ascii_digit()) => Ok(n),
            _ => Err(format!(
                "TEMPER_CXX_JOBS must be a whole number above 0, not {text}"
            )),
        },
    }
}

/// Builds a library's target, in the shared build where [`workspace`]
/// configured it, or else alone in `LIBRARY/build`; the program's path.
fn build(dir: &Path, library: &str, target: &str) -> Result<PathBuf, String> {
    let jobs = jobs()?.to_string();
    let cmake = tool("CMAKE", "cmake");
    let shared = dir.join(WORKSPACE).join("tree");
    let (tree, programs) = match shared.join("CMakeCache.txt").is_file() {
        true => (shared.clone(), shared.join("bin")),
        false => {
            let here = dir.join(library);
            fresh(&here.join("build"), &here.join("build"));
            let configure = output(
                Command::new(&cmake)
                    .args(["-S", ".", "-B", "build", "-DCMAKE_BUILD_TYPE=Debug"])
                    .args(launcher())
                    .current_dir(&here),
                "cmake",
            )?;
            if !configure.status.success() {
                return Err(format!("cmake failed\n{}", tool_output(&configure)));
            }
            write_stamp(
                &here.join("build").join(STAMP),
                &toolchain(&here.join("build")),
            );
            (here.join("build"), here.join("build"))
        }
    };
    let made = output(
        Command::new(&cmake)
            .arg("--build")
            .arg(&tree)
            .args(["--target", target, "-j", &jobs]),
        "cmake --build",
    )?;
    if !made.status.success() {
        return Err(format!("the build failed\n{}", tool_output(&made)));
    }
    Ok(programs.join(format!("{target}{}", std::env::consts::EXE_SUFFIX)))
}

/// The ccache that C++ builds go through, CMake's compiler launcher:
/// `ccache` where it's on `PATH`, unless `TEMPER_NO_CCACHE` is set or
/// `CMAKE_CXX_COMPILER_LAUNCHER` names a launcher of the user's own,
/// which CMake reads itself.
fn ccache() -> Option<PathBuf> {
    let var = |name| std::env::var(name).ok();
    let path = std::env::var_os("PATH");
    choose_ccache(
        var("TEMPER_NO_CCACHE").as_deref(),
        var("CMAKE_CXX_COMPILER_LAUNCHER").as_deref(),
        path.as_deref(),
    )
}

/// [`ccache`], given `TEMPER_NO_CCACHE`, `CMAKE_CXX_COMPILER_LAUNCHER`,
/// and `PATH`; each set but empty is unset.
fn choose_ccache(
    no_ccache: Option<&str>,
    launcher: Option<&str>,
    path: Option<&OsStr>,
) -> Option<PathBuf> {
    let set = |v: Option<&str>| v.is_some_and(|v| !v.is_empty());
    if set(no_ccache) || set(launcher) {
        return None;
    }
    let name = format!("ccache{}", std::env::consts::EXE_SUFFIX);
    std::env::split_paths(path?)
        .map(|dir| dir.join(&name))
        .find(|file| file.is_file())
}

/// CMake's options for [`ccache`], where it's used.
fn launcher() -> Vec<String> {
    (ccache().into_iter())
        .map(|c| format!("-DCMAKE_CXX_COMPILER_LAUNCHER={}", c.display()))
        .collect()
}

/// What `temper test -b cpp` says of [`ccache`], once.
fn note() -> Option<String> {
    ccache().map(|_| "C++ builds go through ccache (TEMPER_NO_CCACHE=1 turns it off)".to_string())
}

fn run(dir: &Path, library: &Tested, _: &[Tested]) -> Result<bool, String> {
    let target = format!("{}-main", library.name);
    let main = build(dir, &library.name, &target)?;
    program(
        limit_memory(&mut Command::new(main)).current_dir(dir.join(&library.name)),
        &target,
    )
}

fn test(dir: &Path, library: &Tested, _: &[Tested]) -> TestResults {
    let here = dir.join(&library.name);
    let tests = build(dir, &library.name, &format!("{}-test", library.name))?;
    let results = here.join("test-results.xml");
    let _ = std::fs::remove_file(&results);
    let run = output(
        limit_memory(&mut Command::new(tests)).current_dir(&here),
        "the tests",
    )?;
    junit_file(&results, &run, str::to_string)
}

#[cfg(test)]
mod tests {
    use super::{choose_ccache, choose_jobs, toolchain_with};
    use std::ffi::OsString;
    use std::path::PathBuf;

    /// A directory holding an executable `ccache`, and a `PATH` of an
    /// empty directory and it.
    fn fake_path(test: &str) -> (PathBuf, OsString) {
        let root = std::env::temp_dir().join(format!("be-cpp-{}-{test}", std::process::id()));
        let (empty, bin) = (root.join("empty"), root.join("bin"));
        std::fs::create_dir_all(&empty).unwrap();
        std::fs::create_dir_all(&bin).unwrap();
        let ccache = bin.join(format!("ccache{}", std::env::consts::EXE_SUFFIX));
        std::fs::write(&ccache, "").unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&ccache, std::fs::Permissions::from_mode(0o755)).unwrap();
        }
        (ccache, std::env::join_paths([empty, bin]).unwrap())
    }

    #[test]
    fn ccache_where_installed() {
        let (ccache, path) = fake_path("installed");
        assert_eq!(choose_ccache(None, None, Some(&path)), Some(ccache));
        // Set but empty is unset.
        let (ccache, path) = fake_path("empty-vars");
        assert_eq!(choose_ccache(Some(""), Some(""), Some(&path)), Some(ccache));
    }

    #[test]
    fn ccache_not_installed() {
        let (_, path) = fake_path("missing");
        let empty = std::env::split_paths(&path).next().unwrap();
        let path = std::env::join_paths([empty]).unwrap();
        assert_eq!(choose_ccache(None, None, Some(&path)), None);
        assert_eq!(choose_ccache(None, None, None), None);
    }

    #[test]
    fn ccache_turned_off() {
        let (_, path) = fake_path("off");
        // `TEMPER_NO_CCACHE`, whatever it's set to.
        assert_eq!(choose_ccache(Some("1"), None, Some(&path)), None);
        assert_eq!(choose_ccache(Some("0"), None, Some(&path)), None);
        // A launcher of the user's own, which CMake reads itself.
        assert_eq!(choose_ccache(None, Some("sccache"), Some(&path)), None);
    }

    /// A build is configured afresh when what CMake reads as it
    /// configures changes: a variable such as `CMAKE_GENERATOR` or
    /// `DEVELOPER_DIR`, or the compiler it found, as its cache names it.
    #[test]
    fn toolchain_keys() {
        let root = std::env::temp_dir().join(format!("be-cpp-{}-key", std::process::id()));
        let tree = root.join("tree");
        std::fs::create_dir_all(&tree).unwrap();
        let none = |_: &str| String::new();
        let key = toolchain_with(&none, &tree);
        assert_eq!(toolchain_with(&none, &tree), key);
        for var in [
            "CMAKE_GENERATOR",
            "CMAKE_TOOLCHAIN_FILE",
            "DEVELOPER_DIR",
            "SDKROOT",
        ] {
            let set = |name: &str| match name == var {
                true => "x".to_string(),
                false => String::new(),
            };
            assert_ne!(toolchain_with(&set, &tree), key, "{var}");
        }
        let compiler = root.join("c++");
        std::fs::write(&compiler, "old").unwrap();
        let cache = format!("CMAKE_CXX_COMPILER:FILEPATH={}\n", compiler.display());
        std::fs::write(tree.join("CMakeCache.txt"), cache).unwrap();
        let found = toolchain_with(&none, &tree);
        assert_ne!(found, key);
        std::fs::write(&compiler, "newer").unwrap();
        assert_ne!(toolchain_with(&none, &tree), found);
        let _ = std::fs::remove_dir_all(root);
    }

    #[test]
    fn jobs_by_default() {
        // As many as there are CPUs, four at most.
        assert_eq!(choose_jobs(None, 1), Ok(1));
        assert_eq!(choose_jobs(None, 2), Ok(2));
        assert_eq!(choose_jobs(None, 4), Ok(4));
        assert_eq!(choose_jobs(None, 16), Ok(4));
        // Set but empty, as a workflow's `TEMPER_CXX_JOBS: ""`, is unset.
        assert_eq!(choose_jobs(Some(""), 8), Ok(4));
    }

    #[test]
    fn jobs_given() {
        // Whatever's given, more than the CPUs or the default too.
        assert_eq!(choose_jobs(Some("1"), 8), Ok(1));
        assert_eq!(choose_jobs(Some("3"), 8), Ok(3));
        assert_eq!(choose_jobs(Some("12"), 2), Ok(12));
    }

    #[test]
    fn jobs_wrong() {
        for wrong in [
            "0",
            "-2",
            "+2",
            "2.5",
            " 2",
            "two",
            "99999999999999999999999",
        ] {
            let why = format!("TEMPER_CXX_JOBS must be a whole number above 0, not {wrong}");
            assert_eq!(choose_jobs(Some(wrong), 8), Err(why));
        }
    }
}
