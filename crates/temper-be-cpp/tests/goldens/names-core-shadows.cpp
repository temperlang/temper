#include <core-shadows/mine.hpp>

namespace core_shadows {

namespace core = temper::core;

namespace temper_globals {

static core::GlobalSlot<int32_t> Boolean;

}  // namespace temper_globals

std::shared_ptr<String> String::make(int32_t text) {
  global_init_mine();
  std::shared_ptr<String> self = std::make_shared<String>();
  self->text = text;
  return self;
}

int32_t String::get_doubled() const {
  return core::Int::mul(this->text, 2);
}

int32_t String::get_text() const {
  return this->text;
}

std::shared_ptr<List> List::make(int32_t n) {
  global_init_mine();
  std::shared_ptr<List> self = std::make_shared<List>();
  self->n = n;
  return self;
}

int32_t List::get_n() const {
  return this->n;
}

int32_t ignore(int32_t x) {
  global_init_mine();
  return core::Int::add(x, 1);
}

int32_t summary() {
  global_init_mine();
  std::shared_ptr<String> s = String::make(3);
  std::shared_ptr<List> l = List::make(4);
  return core::Int::add(core::Int::add(core::Int::add(core::Int::add(s->text, s->get_doubled()), l->n), ignore(10)), temper_globals::Boolean.value);
}

void global_init_mine() {
  core::init_once([] {
    temper_globals::Boolean.construct();
    temper_globals::Boolean.value = 7;
  });
}

}  // namespace core_shadows

