// init.cpp
#include <core-shadows/init.hpp>

namespace core_shadows {

namespace core = temper::core;

static int32_t bump(int32_t console) {
  return core::Int::add(console, 1);
}

void global_init_init() {
  core::init_once([] {
    global_init_mine();
    std::shared_ptr<core::Console::Type> console = core::Console::get_console();
    core::Console::log(console, std::to_string(summary()));
    core::Str s = TEMPER_STR("core's string");
    core::Console::log(console, s);
    std::shared_ptr<std::vector<int32_t>> xs = core::List::make<int32_t>(1, 2);
    core::Console::log(console, std::to_string(core::List::length<int32_t>(xs)));
    core::Console::log(console, std::to_string(bump(5)));
  });
}

}  // namespace core_shadows

